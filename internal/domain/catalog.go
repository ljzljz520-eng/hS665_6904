func ModelsByClass(class string) []ModelSpec {
	out := []ModelSpec{}
	for _, m := range ModelCatalog {
		if class == "" || m.Class == class {
			out = append(out, m)
		}
	}
	return out
}
func CapacityRange(min, max int) []ModelSpec {
	out := []ModelSpec{}
	for _, m := range ModelCatalog {
		if m.Capacity >= min && (max <= 0 || m.Capacity <= max) {
			out = append(out, m)
		}
	}
	return out
}
