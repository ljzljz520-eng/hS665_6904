func Zone(zone string) (ZoneRule, bool) {
	for _, r := range ZoneRules {
		if r.Zone == zone {
			return r, true
		}
	}
	return ZoneRule{}, false
}
func Permitted(zone string, load int, permit bool) bool {
	r, ok := Zone(zone)
	if !ok {
		return false
	}
	if load > r.MaxLoad {
		return false
	}
	return !r.RequiresPermit || permit
}
