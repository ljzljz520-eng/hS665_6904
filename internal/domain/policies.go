func PolicyFor(code string) (Policy, bool) {
	for _, p := range Policies {
		if p.Code == code {
			return p, true
		}
	}
	return Policy{}, false
}
func PoliciesAbove(n int) []Policy {
	out := []Policy{}
	for _, p := range Policies {
		if p.Threshold >= n {
			out = append(out, p)
		}
	}
	return out
}
func ActionForLoad(load int) string {
	for _, p := range Policies {
		if load <= p.Threshold {
			return p.Action
		}
	}
	return "hold"
}
